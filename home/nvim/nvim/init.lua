-- ==================== Neovim 配置入口文件 ====================
-- 这是 Neovim 启动时首先加载的文件
-- 它负责加载所有其他配置模块
-- 文件位置：~/.config/nvim/init.lua

-- ==================== 插件管理器配置 ====================
-- 加载 lazy.nvim 插件管理器配置
-- lazy.nvim 是一个现代化的 Neovim 插件管理器
-- 特点：延迟加载、自动安装、快速启动
-- 配置文件：lua/config/lazy.lua
require("config.lazy")

-- ==================== 核心配置加载 ====================
-- 加载键位映射（快捷键）配置
-- 包含所有自定义的快捷键设置
-- 如：leader 键、窗口导航、文件操作等
-- 配置文件：lua/core/keymaps.lua
require("core.keymaps")

-- 加载编辑器选项配置
-- 包含所有 Neovim 的基础设置
-- 如：缩进、行号、搜索、颜色方案等
-- 配置文件：lua/core/options.lua
require("core.options")

-- ==================== 配置加载顺序说明 ====================
-- 1. lazy.nvim：首先加载插件管理器，准备插件环境
-- 2. keymaps：然后加载快捷键，这样插件可以使用这些键位
-- 3. options：最后加载编辑器选项，设置编辑环境
--
-- 注意：插件的具体配置在 lua/config/plugins/ 目录下
-- 这些配置会被 lazy.nvim 自动加载
